/** Sem acento e em minúsculas — usado nos dois lados da busca. */
function fold(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}

/**
 * Índice de busca montado uma vez: emoji + palavras-chave dos TRÊS idiomas, já
 * normalizadas, mais o nome da categoria também nos três — "smileys", "sonrisas" e
 * "carinhas" levam todos à mesma aba.
 *
 * Antes daqui entrava `c.label`, que hoje é a CHAVE do catálogo: a busca casava com
 * 'emoji.catSmileys', o nome interno, e nunca com o nome que a pessoa lê.
 *
 * Por unir os três, ele pode continuar sendo constante de módulo sem cair na armadilha
 * de sempre: não há idioma ativo dentro dele para congelar.
 */
const SEARCH_INDEX: { item: EmojiEntry; hay: string }[] = EMOJI_CATEGORIES.flatMap((c) =>
  c.items.map((item) => ({ item, hay: fold(`${TRADUCOES[c.label].join(' ')} ${item.k.join(' ')}`) })),
)

/** Busca por palavra-chave (acento-insensível). Query vazia devolve lista vazia. */
export function searchEmojis(query: string, limit = 120): EmojiEntry[] {
  const q = fold(query.trim())
  if (!q) return []
  const terms = q.split(/\s+/)
  const out: EmojiEntry[] = []
  for (const { item, hay } of SEARCH_INDEX) {
    if (terms.every((t) => hay.includes(t))) out.push(item)
    if (out.length >= limit) break
  }
  return out
}

/**
 * A primeira palavra-chave NO IDIOMA DA TELA — é o `title` do botão na grade,
 * o balãozinho que diz o que é aquele desenho de 23px.
 *
 * Aqui, ao contrário da busca, mostrar os três idiomas de uma vez não ajudaria
 * ninguém: "sorriso sonrisa smile" não é tradução, é ruído.
 */
export function rotuloEmoji(item: EmojiEntry): string {
  const palavras = item.k[indiceIdioma()] || item.k[0]
  return palavras.split(' ')[0] ?? ''
}

/** Todos os emojis do catálogo, indexados pelo caractere — resolve os "frequentes" salvos. */
const BY_CHAR = new Map(EMOJI_CATEGORIES.flatMap((c) => c.items).map((i) => [i.e, i]))

export function emojiByChar(char: string): EmojiEntry | undefined {
  return BY_CHAR.get(char)
}
