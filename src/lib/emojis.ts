// Catálogo de emojis do seletor (src/components/common/EmojiPicker.tsx).
//
// As categorias e a ordem seguem o teclado de emoji do iPhone. O DESENHO de cada emoji vem
// da fonte do sistema — em iPhone/Mac já é a arte da Apple, no Windows/Android é a da própria
// plataforma. Servir a arte da Apple em qualquer aparelho exigiria baixar as imagens de uma
// CDN externa, coisa que este app não faz.
//
// `k` são as palavras-chave da busca, nos três idiomas, com sinônimos comuns. A busca
// normaliza acentos dos dois lados (ver `searchEmojis`), então "coracao" acha "coração".
//
// A BUSCA OLHA OS TRÊS AO MESMO TEMPO, e não só o idioma da tela. Quem pôs o CRM em inglês
// e digita "coração" acha o coração; quem está em português e digita "heart" também.
// Procurar é tentar lembrar — achar demais ajuda, achar de menos irrita. De quebra, o
// índice deixa de depender do idioma ativo e não precisa ser refeito a cada troca.

export interface EmojiEntry {
  /** O caractere em si. */
  e: string
  /**
   * Palavras-chave da busca, separadas por espaço, uma lista por idioma:
   * [pt, es, en]. Mesma forma do catálogo — e pelo mesmo motivo, já que aqui
   * também uma tupla incompleta não compila.
   */
  k: [string, string, string]
}

export interface EmojiCategory {
  id: string
  /** Rótulo exibido acima da grade. */
  /** Chave do catálogo — o rótulo é traduzido em quem desenha o seletor. */
  label: Chave
  /** Emoji usado como ícone da aba (mesma ideia das abas do iPhone). */
  icon: string
  items: EmojiEntry[]
}

